"""
Script 02: Prepare cross-dataset response and drug fingerprint data.

Purpose
-------
Takes the cleaned standardised GDSC2 response dataset from the previous script
and the standardised CTRPv2 response dataset.

The script:
1. Loads the already-cleaned standardised GDSC2 response dataset.
2. Loads the standardised CTRPv2 response dataset.
3. Keeps the required response columns for each dataset.
4. Removes rows with missing response values from CTRPv2.
5. Removes duplicate cell-line/drug pairs from CTRPv2.
6. Identifies CTRPv2 cell lines that are unseen in clean GDSC2.
7. Saves the clean CTRPv2 response table.
8. Saves the CTRPv2 response table containing only cell lines unseen
   in GDSC2.
9. Transposes the raw drug fingerprint data for both datasets.

Response columns retained:

GDSC2:
    cellosaurus_id
    cell_line_name
    pubchem_id
    LN_IC50_curvecurator
    LN_IC50_standardised
    tissue

CTRPv2:
    cellosaurus_id
    cell_line_name
    pubchem_id
    LN_IC50_curvecurator
    LN_IC50_curvecurator_normalised
    LN_IC50_standardised
    tissue
"""

import pandas as pd


# ============================================================
# Configuration
# ============================================================

Data_root = (
    "/Users/manellamukangwa/Honours-Cancer-Drug-Response-Project/"
    "Projects/Cancer-Drug-Response-Prediction/data"
)


# ============================================================
# Dataset A: GDSC2 reference dataset
# ============================================================

Dataset_A_name = "GDSC2"

# Already-cleaned standardised GDSC2 from Script 01
Dataset_A_response_clean = (
    f"{Data_root}/processed/GDSC2_response_standardised_clean.csv"
)

# Raw GDSC2 drug fingerprints
Dataset_A_fingerprint_raw = (
    f"{Data_root}/raw/GDSC2/drug_fingerprints/"
    "pubchem_id_to_demorgan_128_map.csv"
)

# Output: transposed GDSC2 fingerprints
Dataset_A_fingerprints_transposed = (
    f"{Data_root}/processed/GDSC2_fingerprints_128_transposed.csv"
)


# ============================================================
# Dataset B: CTRPv2 external dataset
# ============================================================

Dataset_B_name = "CTRPv2"

# Standardised CTRPv2 generated by the standardisation script
Dataset_B_response_raw = (
    f"{Data_root}/processed/CTRPv2_standardised.csv"
)

# Clean standardised CTRPv2 response table
Dataset_B_response_clean = (
    f"{Data_root}/processed/CTRPv2_response_clean.csv"
)

# CTRPv2 cell lines that are unseen in GDSC2
Dataset_B_response_unseen = (
    f"{Data_root}/processed/CTRPv2_response_unseen_in_GDSC2.csv"
)

# Raw CTRPv2 drug fingerprints
Dataset_B_fingerprint_raw = (
    f"{Data_root}/raw/CTRPv2/drug_fingerprints/"
    "pubchem_id_to_demorgan_128_map.csv"
)

# Output: transposed CTRPv2 fingerprints
Dataset_B_fingerprints_transposed = (
    f"{Data_root}/processed/CTRPv2_fingerprints_128_transposed.csv"
)


# ============================================================
# Column configuration
# ============================================================

# Columns retained from GDSC2
Dataset_A_response_columns = [
    "cellosaurus_id",
    "cell_line_name",
    "pubchem_id",
    "LN_IC50_standardised",
    "tissue"
]

# Columns retained from CTRPv2
Dataset_B_response_columns = [
    "cellosaurus_id",
    "cell_line_name",
    "pubchem_id",
    "LN_IC50_curvecurator_normalised",
    "LN_IC50_standardised",
    "tissue"
]

Cell_line_identifier = "cell_line_name"
Drug_identifier = "pubchem_id"

# GDSC2 uses the standardised response
Dataset_A_response_column = "LN_IC50_standardised"

# CTRPv2 uses the standardised response
Dataset_B_response_column = "LN_IC50_standardised"


# ============================================================
# Load clean GDSC2
# ============================================================

def load_clean_dataset_a() -> pd.DataFrame:
    """
    Load the already-cleaned standardised GDSC2 response dataset.

    GDSC2 is the reference dataset and its standardised response
    values are retained.
    """

    print(
        f"Reading clean {Dataset_A_name} response table ..."
    )

    df = pd.read_csv(
        Dataset_A_response_clean,
        dtype={
            "cellosaurus_id": str,
            Cell_line_identifier: str,
            Drug_identifier: str,
            "tissue": str
        },
        low_memory=False,
    )

    df = df[Dataset_A_response_columns].copy()

    print(
        f"Loaded clean {Dataset_A_name}: "
        f"{len(df)} rows"
    )

    return df


# ============================================================
# Clean standardised CTRPv2
# ============================================================

def clean_dataset_b_response() -> pd.DataFrame:
    """
    Load the standardised CTRPv2 response dataset.

    Keeps the required response columns, removes rows with
    missing standardised response values, and removes duplicate
    cell-line/drug pairs.
    """

    print(
        f"Reading standardised {Dataset_B_name} response table ..."
    )

    df = pd.read_csv(
        Dataset_B_response_raw,
        dtype={
            "cellosaurus_id": str,
            Cell_line_identifier: str,
            Drug_identifier: str,
            "tissue": str
        },
        low_memory=False,
    )

    # Keep only the required columns
    df = df[Dataset_B_response_columns].copy()

    # Remove rows with missing standardised response values
    df = df.dropna(
        subset=[Dataset_B_response_column]
    )

    # Remove duplicate cell-line/drug pairs
    df = df.drop_duplicates(
        subset=[
            Cell_line_identifier,
            Drug_identifier
        ]
    )

    # Save clean standardised CTRPv2
    df.to_csv(
        Dataset_B_response_clean,
        index=False
    )

    print(
        f"Saved clean standardised {Dataset_B_name} response table "
        f"({len(df)} rows) -> {Dataset_B_response_clean}"
    )

    return df


# ============================================================
# Find unseen CTRPv2 cell lines
# ============================================================

def find_unseen_dataset_b_cell_lines(
    dataset_a_clean: pd.DataFrame,
    dataset_b_clean: pd.DataFrame
) -> pd.DataFrame:
    """
    Identify CTRPv2 cell lines that are not present in GDSC2.
    """

    dataset_a_cell_lines = set(
        dataset_a_clean[
            Cell_line_identifier
        ].unique()
    )

    dataset_b_cell_lines = set(
        dataset_b_clean[
            Cell_line_identifier
        ].unique()
    )

    unseen_cell_lines = (
        dataset_b_cell_lines - dataset_a_cell_lines
    )

    print(
        f"\n{Dataset_A_name} has "
        f"{len(dataset_a_cell_lines)} unique cell lines."
    )

    print(
        f"{Dataset_B_name} has "
        f"{len(dataset_b_cell_lines)} unique cell lines."
    )

    print(
        f"{len(unseen_cell_lines)} {Dataset_B_name} cell lines "
        f"are unseen in {Dataset_A_name}."
    )

    # Keep only CTRPv2 rows belonging to unseen cell lines
    unseen_df = dataset_b_clean[
        dataset_b_clean[
            Cell_line_identifier
        ].isin(unseen_cell_lines)
    ].copy()

    # Save unseen-cell-line response table
    unseen_df.to_csv(
        Dataset_B_response_unseen,
        index=False
    )

    print(
        f"Saved unseen-cell-line {Dataset_B_name} response table "
        f"({len(unseen_df)} rows) -> "
        f"{Dataset_B_response_unseen}"
    )

    return unseen_df


# ============================================================
# Transpose drug fingerprints
# ============================================================

def transpose_fingerprints(
    raw_path: str,
    out_path: str,
    dataset_label: str
) -> None:
    """
    Transpose the drug fingerprint table so that each drug is a row.
    """

    print(
        f"\nTransposing {dataset_label} fingerprints ..."
    )

    fingerprint = pd.read_csv(
        raw_path,
        index_col=None
    ).T

    fingerprint.index.name = Drug_identifier

    fingerprint.to_csv(
        out_path
    )

    print(
        f"Saved transposed {dataset_label} fingerprints "
        f"({fingerprint.shape[0]} drugs) -> {out_path}"
    )


# ============================================================
# Main
# ============================================================

if __name__ == "__main__":

    # --------------------------------------------------------
    # 1. Load already-cleaned standardised GDSC2
    # --------------------------------------------------------

    dataset_a_clean = load_clean_dataset_a()


    # --------------------------------------------------------
    # 2. Clean standardised CTRPv2
    # --------------------------------------------------------

    dataset_b_clean = clean_dataset_b_response()


    # --------------------------------------------------------
    # 3. Find CTRPv2 cell lines unseen in GDSC2
    # --------------------------------------------------------

    find_unseen_dataset_b_cell_lines(
        dataset_a_clean,
        dataset_b_clean
    )


    # --------------------------------------------------------
    # 4. Transpose GDSC2 fingerprints
    # --------------------------------------------------------

    transpose_fingerprints(
        Dataset_A_fingerprint_raw,
        Dataset_A_fingerprints_transposed,
        Dataset_A_name
    )


    # --------------------------------------------------------
    # 5. Transpose CTRPv2 fingerprints
    # --------------------------------------------------------

    transpose_fingerprints(
        Dataset_B_fingerprint_raw,
        Dataset_B_fingerprints_transposed,
        Dataset_B_name
    )